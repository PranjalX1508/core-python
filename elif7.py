# Take a number from 1–7 and print the corresponding day of the week.

day_num=int(input("Day Number is:"))
if day_num==1:
    print("Monday")
elif day_num==2:
    print("Tuesday")
elif day_num==3:
    print("Wednesday")
elif day_num==4:
    print("Thrusday")
elif day_num==5:
    print("Friday")
elif day_num==6:
    print("Saturday")
else:
    print("Sunday")